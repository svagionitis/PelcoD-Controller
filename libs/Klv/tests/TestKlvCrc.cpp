#include "KlvCrc.h"
#include <gtest/gtest.h>
#include <vector>

using namespace Klv;

TEST(KlvCrcTest, BasicCrcCalculation) {
    // Standard ASCII "123456789" with CCITT poly 0x1021, init 0x0000
    // Check value is 0x31C3
    const std::uint8_t data[] = { '1', '2', '3', '4', '5', '6', '7', '8', '9' };
    const std::uint16_t crc = KlvCrc::calculate(data, sizeof(data));
    EXPECT_EQ(crc, 0x31C3U);
}

TEST(KlvCrcTest, Tag1ChecksumAndVerification) {
    std::vector<std::uint8_t> testPacket = {
        0x06, 0x0E, 0x2B, 0x34, 0x02, 0x0B, 0x01, 0x01, 0x0E, 0x01, 0x03, 0x01, 0x01, 0x00, 0x00, 0x00,
        0x06, // BER length (6 bytes: tag 65 + tag 1)
        0x41, 0x01, 0x05, // Tag 65 (0x41), len 1, val 5
        0x01, 0x02 // Tag 1 (0x01), len 2
    };

    const std::uint16_t tag1Crc = KlvCrc::computeChecksumForTag1(testPacket.data(), testPacket.size());
    testPacket.push_back(static_cast<std::uint8_t>((tag1Crc >> 8U) & 0xFFU));
    testPacket.push_back(static_cast<std::uint8_t>(tag1Crc & 0xFFU));

    // Verifying complete packet with CRC appended should succeed
    EXPECT_TRUE(KlvCrc::verifyPacket(testPacket.data(), testPacket.size()));

    // Corrupt one byte
    testPacket[18] ^= 0xFFU;
    EXPECT_FALSE(KlvCrc::verifyPacket(testPacket.data(), testPacket.size()));
}

TEST(KlvCrcTest, NullOrEmptyData) {
    EXPECT_EQ(KlvCrc::calculate(nullptr, 10U), 0U);
    EXPECT_EQ(KlvCrc::calculate(nullptr, 0U), 0U);
    EXPECT_EQ(KlvCrc::computeBcc16(nullptr, 10U), 0U);
    EXPECT_EQ(KlvCrc::computeBcc16(nullptr, 0U), 0U);
    EXPECT_FALSE(KlvCrc::verifyPacket(nullptr, 10U));
    EXPECT_FALSE(KlvCrc::verifyPacket(nullptr, 0U));
}

TEST(KlvCrcTest, Misb0601Bcc16CalculationAndVerification) {
    // Authentic MISB ST 0601 packet from sample flight video (163 bytes total)
    const std::vector<std::uint8_t> flightPacket = {
        0x06, 0x0E, 0x2B, 0x34, 0x02, 0x0B, 0x01, 0x01, 0x0E, 0x01, 0x03, 0x01, 0x01, 0x00, 0x00, 0x00,
        0x81, 0x91, 0x02, 0x08, 0x00, 0x04, 0x6C, 0x8E, 0x20, 0x03, 0x83, 0x85, 0x41, 0x01, 0x01, 0x05,
        0x02, 0x3D, 0x3B, 0x06, 0x02, 0x15, 0x80, 0x07, 0x02, 0x01, 0x52, 0x0B, 0x03, 0x45, 0x4F, 0x4E,
        0x0C, 0x0E, 0x47, 0x65, 0x6F, 0x64, 0x65, 0x74, 0x69, 0x63, 0x20, 0x57, 0x47, 0x53, 0x38, 0x34,
        0x0D, 0x04, 0x4D, 0xC4, 0xDC, 0xBB, 0x0E, 0x04, 0xB1, 0xA8, 0x6C, 0xFE, 0x0F, 0x02, 0x1F, 0x4A,
        0x10, 0x02, 0x00, 0x85, 0x11, 0x02, 0x00, 0x4B, 0x12, 0x04, 0x20, 0xC8, 0xD2, 0x7D, 0x13, 0x04,
        0xFC, 0xDD, 0x02, 0xD8, 0x14, 0x04, 0xFE, 0xB8, 0xCB, 0x61, 0x15, 0x04, 0x00, 0x8F, 0x3E, 0x61,
        0x16, 0x04, 0x00, 0x00, 0x01, 0xC9, 0x17, 0x04, 0x4D, 0xDD, 0x8C, 0x2A, 0x18, 0x04, 0xB1, 0xBE,
        0x9E, 0xF4, 0x19, 0x02, 0x0B, 0x85, 0x28, 0x04, 0x4D, 0xDD, 0x8C, 0x2A, 0x29, 0x04, 0xB1, 0xBE,
        0x9E, 0xF4, 0x2A, 0x02, 0x0B, 0x85, 0x38, 0x01, 0x2E, 0x39, 0x04, 0x00, 0x8D, 0xD4, 0x29, 0x01,
        0x02, 0x1C, 0x5F
    };

    ASSERT_EQ(flightPacket.size(), 163U);

    // Compute BCC-16 over first 161 bytes (up to Tag 1 Length 0x02)
    const std::uint16_t bcc = KlvCrc::computeBcc16(flightPacket.data(), 161U);
    EXPECT_EQ(bcc, 0x1C5FU);

    // Verifying complete packet with stored BCC-16 (0x1C5F) must succeed
    EXPECT_TRUE(KlvCrc::verifyPacket(flightPacket.data(), flightPacket.size()));

    // Corrupt one byte and verify rejection
    std::vector<std::uint8_t> corrupted = flightPacket;
    corrupted[50] ^= 0x55U;
    EXPECT_FALSE(KlvCrc::verifyPacket(corrupted.data(), corrupted.size()));
}

